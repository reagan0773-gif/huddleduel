// Copies the game's three typefaces from the installed @fontsource packages
// into www/fonts and writes www/fonts/fonts.css, so the app works offline.
// If a face is missing, the game falls back to system fonts.
import fs from 'node:fs';
import path from 'node:path';

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const outDir = path.join(root, 'www', 'fonts');
fs.mkdirSync(outDir, { recursive: true });

const faces = [
  { family: 'Graduate', pkg: 'graduate', weights: [400] },
  { family: 'Barlow Semi Condensed', pkg: 'barlow-semi-condensed', weights: [400, 500, 600, 700] },
  { family: 'Chivo Mono', pkg: 'chivo-mono', weights: [500, 700] },
];

let css = '/* Generated by scripts/copy-fonts.mjs */\n';
let missing = 0;
for (const f of faces) {
  const dir = path.join(root, 'node_modules', '@fontsource', f.pkg, 'files');
  const files = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
  for (const w of f.weights) {
    const name = files.find(n => n.endsWith(`-latin-${w}-normal.woff2`) && !n.includes('-ext-'));
    if (!name) { console.warn(`! ${f.family} ${w} not found; the system font will be used.`); missing++; continue; }
    fs.copyFileSync(path.join(dir, name), path.join(outDir, name));
    css += `@font-face{font-family:"${f.family}";font-style:normal;font-weight:${w};font-display:swap;src:url("${name}") format("woff2")}\n`;
  }
}
fs.writeFileSync(path.join(outDir, 'fonts.css'), css);
console.log(`Fonts copied to www/fonts${missing ? ` (${missing} missing)` : ''}.`);
